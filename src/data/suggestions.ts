// Build flattened deduplicated catalog at module initialization
const seenNormalized = new Set<string>();
export const ALL_SUGGESTIONS: SuggestionItem[] = [];

(Object.keys(RAW_SUGGESTIONS) as CategoryId[]).forEach((category) => {
  for (const title of RAW_SUGGESTIONS[category]) {
    const clean = title.trim();
    const norm = normalizeUzbek(clean);
    if (clean && !seenNormalized.has(norm)) {
      seenNormalized.add(norm);
      ALL_SUGGESTIONS.push({ nomi: clean, toifa: category });
    }
  }
});

/**
 * Returns up to `limit` (default 8) smart suggestions matching `query`.
 * User history items matching the query appear at the very top!
 */
export function getSmartSuggestions(
  query: string,
  userHistory: UserHistoryItem[],
  limit = 8,
): SuggestionItem[] {
  const q = normalizeUzbek(query);
  if (!q) return [];

  const results: SuggestionItem[] = [];
  const used = new Set<string>();

  // 1. User's own previously written tasks at the very top
  const historyMatches: Array<{ item: UserHistoryItem; rank: number }> = [];
  for (const h of userHistory) {
    const rank = getUzbekMatchRank(h.nomi, q);
    if (rank >= 0) {
      historyMatches.push({ item: h, rank });
    }
  }
  historyMatches.sort((a, b) => {
    if (a.rank !== b.rank) return a.rank - b.rank;
    return b.item.lastUsedAt - a.item.lastUsedAt;
  });

  for (const { item } of historyMatches) {
    const norm = normalizeUzbek(item.nomi);
    if (!used.has(norm)) {
      used.add(norm);
      results.push({
        nomi: item.nomi,
        toifa: item.toifa,
        fromHistory: true,
      });
      if (results.length >= limit) return results;
    }
  }

  // 2. Built-in 1000+ Uzbek suggestion catalog
  const catalogMatches: Array<{ item: SuggestionItem; rank: number }> = [];
  for (const item of ALL_SUGGESTIONS) {
    const norm = normalizeUzbek(item.nomi);
    if (used.has(norm)) continue;
    const rank = getUzbekMatchRank(item.nomi, q);
    if (rank >= 0) {
      catalogMatches.push({ item, rank });
    }
  }

  catalogMatches.sort((a, b) => {
    if (a.rank !== b.rank) return a.rank - b.rank;
    return a.item.nomi.localeCompare(b.item.nomi, 'uz');
  });

  for (const { item } of catalogMatches) {
    results.push(item);
    if (results.length >= limit) break;
  }

  return results;
}
